#!/bin/sh
# Generate a target's preprocessor tables (src/arch/predef_<target>.h):
# the macros the target's compiler predefines, and for clang targets the
# answers to every __has_feature / __has_builtin / __is_target_* query the
# SDK headers make. kcc then preprocesses without the host compiler.
#
#   tools/predef.sh arm64-macos            # from the host's clang and SDK
#   tools/predef.sh x86_64-linux dM.txt    # from a saved `gcc -E -dM -std=gnu89 - </dev/null`
#
# Lines are stored without `#define `; a backslash or quote in a body is
# escaped. `__STRICT_ANSI__` is left out (it depends on -std) and macros
# whose names are not reserved identifiers (`linux`, `unix`) go to a
# separate list that is only defined outside strict mode.
set -e
target=$1
case "$target" in
    arm64-macos|x86_64-linux) ;;
    *) echo "usage: tools/predef.sh arm64-macos | x86_64-linux dM.txt" >&2; exit 2 ;;
esac
cd "$(dirname "$0")/.."
out=src/arch/predef_$(echo "$target" | tr - _).h
# the tables carry the backend's prefix, so both backends can live in one translation unit (the amalgamation)
case "$target" in arm64-macos) prefix=a64_ ;; *) prefix=x64_ ;; esac
tmp=$(mktemp -d) || exit 1
trap 'rm -rf "$tmp"' EXIT

if [ "$target" = arm64-macos ]; then
    echo | cc -E -dM -std=c90 - > "$tmp/dm"
    sdk=$(xcrun --show-sdk-path)
    res=$(cc -print-resource-dir)/include
    # every feature query spelled in the headers, with whitespace removed
    grep -rhoE "(__has_(feature|extension|attribute|builtin|cpp_attribute|declspec_attribute|c_attribute|warning)|__is_target_[a-z_]+|__building_module|__is_identifier)[[:space:]]*\([[:space:]]*[^()]+[[:space:]]*\)" \
        "$sdk/usr/include" "$res" 2>/dev/null | sed 's/[[:space:]]//g' | grep -v '\.\.\.' > "$tmp/q1"
    # queries also arrive through macro parameters (`__supports_builtin(b, ...)` asks
    # `__has_builtin(b)`), so ask about every builtin and attribute name the headers mention
    # (the SDK only: the compiler's own headers name thousands of vector intrinsics)
    grep -rhoE "__builtin_[A-Za-z0-9_]+" "$sdk/usr/include" 2>/dev/null | sort -u | sed 's/^/__has_builtin(/; s/$/)/' > "$tmp/q2"
    grep -rhoE "__attribute__[[:space:]]*\(\([[:space:]]*[A-Za-z_][A-Za-z0-9_]*" "$sdk/usr/include" 2>/dev/null | sed 's/.*(//' | sort -u | sed 's/^/__has_attribute(/; s/$/)/' > "$tmp/q3"
    cat "$tmp/q1" "$tmp/q2" "$tmp/q3" | sort -u > "$tmp/queries"
    # ask clang about each one; the index survives macro expansion where the query would not
    awk '{printf "#if %s\nHAS %d 1\n#else\nHAS %d 0\n#endif\n", $0, NR, NR}' "$tmp/queries" > "$tmp/has.c"
    cc -E -P -std=c90 "$tmp/has.c" 2>"$tmp/has.err" | awk '$1 == "HAS" {print $2, $3}' > "$tmp/has.idx"
    # a query clang itself rejects is dropped
    grep -oE 'has\.c:[0-9]+' "$tmp/has.err" | sed 's/.*://' | awk '{print int(($1 - 1) / 5) + 1}' | sort -u > "$tmp/bad"
    awk 'NR == FNR {v[$1] = $2; next} FILENAME == ARGV[2] {bad[$1] = 1; next} !(FNR in bad) {print $0, v[FNR]}' \
        "$tmp/has.idx" "$tmp/bad" "$tmp/queries" > "$tmp/answers"
else
    [ -n "$2" ] || { echo "x86_64-linux needs the saved gcc -dM output" >&2; exit 2; }
    cp "$2" "$tmp/dm"
    : > "$tmp/answers"
fi

esc() { sed 's/\\/\\\\/g; s/"/\\"/g'; }

{
    echo "/* Generated by tools/predef.sh $target. Do not edit. */"
    echo
    echo "static const char *const ${prefix}predefined_macros[] = {"
    grep '^#define ' "$tmp/dm" | sed 's/^#define //' | grep -v '^__STRICT_ANSI__ ' | grep '^_' | sort | esc | sed 's/^/    "/; s/$/",/'
    echo "    NULL"
    echo "};"
    echo
    echo "/* defined only outside strict ISO mode */"
    echo "static const char *const ${prefix}nonstrict_macros[] = {"
    grep '^#define ' "$tmp/dm" | sed 's/^#define //' | grep -v '^_' | sort | esc | sed 's/^/    "/; s/$/",/'
    echo "    NULL"
    echo "};"
    echo
    echo "/* answers to the feature queries the system headers make; anything else is 0 */"
    echo "static const CppHasAnswer ${prefix}has_answers[] = {"
    awk '{v = $NF; q = $0; sub(/ [01]$/, "", q); gsub(/\\/, "\\\\", q); gsub(/"/, "\\\"", q); printf "    { \"%s\", %s },\n", q, v}' "$tmp/answers"
    echo "    { NULL, 0 }"
    echo "};"
} > "$out"
echo "wrote $out: $(grep -c '^    "' "$out") macros, $(grep -c '^    { "' "$out") feature answers"
