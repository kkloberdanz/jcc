#!/bin/sh
# The amalgamation (Step 19 of the plan): the library as one kcc.c and
# one kcc.h, the way SQLite is distributed, so a host adds one file to
# its build instead of linking libkcc.a. kcc.h is src/kcc.h verbatim.
# kcc.c is a preamble (the commit and the date), the union of the system
# includes, then every file the library is built from in the Makefile's
# order: each header once, inlined where it is first included, then
# every .c file but the driver, y.tab.c last (its prologue defines
# YYSTYPE and YYLTYPE, which nothing after it may see). An include of a
# file already emitted, or of a system header, is replaced by a comment
# on the same line, and a #line directive at every boundary points
# diagnostics and debuggers back at src/. KCC_AMALGAMATION is defined
# so a source can tell, though nothing should need to.
# Usage: tools/amalgamate.sh [DIR]  (default: dist). From the repository
# root (make amalgamation does); y.tab.c must exist (make first).
cd "$(dirname "$0")/.." || exit 1
out=${1:-dist}
[ -f y.tab.c ] || { echo "no y.tab.c: run make first" >&2; exit 1; }
mkdir -p "$out" || exit 1
cp src/kcc.h "$out/kcc.h" || exit 1

commit=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
[ -z "$(git status --porcelain src 2>/dev/null)" ] || commit="$commit, with uncommitted changes"
date=$(date +%Y-%m-%d)

# the library's translation units, in the Makefile's order; the driver (src/main.c) is a client of the library
sources=$(echo $(ls src/*.c | grep -v '^src/main\.c$'; ls src/arch/arch.*.c src/as/*.c; echo y.tab.c))
# the public header first, then every other header (inlining pulls in what each one includes, so the order
# of the rest only decides where a header that nothing earlier needs lands)
headers="src/kcc.h $(echo $(ls src/*.h src/as/*.h | grep -v '^src/kcc\.h$'))"
# the system headers the sources include, hoisted to the top; y.tab.c keeps its own (bison guards them)
system=$(grep -h '^#include <' src/*.c src/*.h src/arch/*.c src/arch/*.h src/as/*.c src/as/*.h | sort -u)

{
    cat <<END
/*
 * kcc.c: the kcc C compiler as one translation unit, generated by
 * tools/amalgamate.sh on $date from commit $commit.
 * Do not edit: edit src/ and regenerate. The public interface is kcc.h
 * (also embedded below). Build it with any C89 compiler, for example
 *     cc -std=gnu89 -c kcc.c
 * with the KCC_ARM64_MACOS_SYSROOT, KCC_ARM64_MACOS_RESOURCE_INC,
 * KCC_X86_64_LINUX_SYSROOT and KCC_X86_64_LINUX_GCC_DIR macros naming
 * each target's default header locations (see the Makefile); a host
 * can override them at run time with -isysroot and -I.
 */
#define KCC_AMALGAMATION 1

$system

END
    awk -v headers="$headers" -v sources="$sources" '
    function resolve(from, name,    d, cand) {
        d = from; sub(/\/[^\/]*$/, "", d); if (d == from) d = ".";
        cand = d "/" name; if (exists(cand)) return canon(cand);
        cand = "src/" name; if (exists(cand)) return canon(cand);
        if (exists(name)) return canon(name);
        return "";
    }
    function exists(p,    r) { r = (getline line < p); close(p); return r >= 0 }
    function canon(p) { sub(/^\.\//, "", p); gsub(/\/\.\//, "/", p); return p }
    function emit(path,    line, n, name, inc) {
        if (path in done) return;
        done[path] = 1;
        n = 0;
        printf "#line 1 \"%s\"\n", path;
        while ((getline line < path) > 0) {
            n++;
            if (line ~ /^#include "/) {
                name = line; sub(/^#include "/, "", name); sub(/".*$/, "", name);
                inc = resolve(path, name);
                if (inc == "") { printf "amalgamate: %s:%d: cannot resolve %s\n", path, n, name > "/dev/stderr"; exit 1 }
                if (inc in done) {
                    printf "/* #include \"%s\" */\n", name;
                } else {
                    emit(inc);
                    printf "#line %d \"%s\"\n", n + 1, path;
                }
            } else if (line ~ /^#include </ && path != "y.tab.c") {
                sub(/^#include /, "/* #include ", line); sub(/>.*$/, ">", line);
                print line " */";
            } else {
                print line;
            }
        }
        close(path);
    }
    BEGIN {
        m = split(headers, h, " ");
        for (i = 1; i <= m; i++) if (h[i] != "") emit(h[i]);
        m = split(sources, s, " ");
        for (i = 1; i <= m; i++) if (s[i] != "") emit(s[i]);
    }'
} >"$out/kcc.c" || exit 1
echo "$out/kcc.c: $(wc -l <"$out/kcc.c" | tr -d ' ') lines; $out/kcc.h"
